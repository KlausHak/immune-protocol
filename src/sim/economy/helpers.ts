/**
 * [economy] Read-only helpers for the AI, controls and HUD (findBuildSpot lives in placement.ts).
 */
import type { Entity, EntityId, PlayerId } from '../../core/types';
import type { World } from '../World';
import { INCOME_HISTORY, INCOME_WINDOW } from './constants';
import { getRuntime } from './state';

/** Alive workers of the player with an empty order queue (F1 "idle worker", AI re-assignment). */
export function idleWorkers(world: World, playerId: PlayerId): Entity[] {
  return world.entitiesOf(playerId, (e) => e.kind === 'unit' && !!e.gatherer && e.orders.length === 0);
}

/**
 * Income per minute over a rolling window (default 60 s; shorter while the match is younger than the window):
 * matter = delivered by workers (incl. gatherMul), energy = generated by buildings.
 */
export function incomeRate(world: World, playerId: PlayerId, windowSec = INCOME_WINDOW): { matterPerMin: number; energyPerMin: number } {
  const p = world.players.get(playerId);
  if (!p) return { matterPerMin: 0, energyPerMin: 0 };
  const rt = getRuntime(world);
  const now = world.time;
  if (!rt) {
    if (now <= 0) return { matterPerMin: 0, energyPerMin: 0 };
    return { matterPerMin: (p.stats.matterGathered / now) * 60, energyPerMin: (p.stats.energyGenerated / now) * 60 };
  }
  const instantEnergy = (rt.energyPerSec.get(playerId) ?? 0) * 60;
  const s = rt.samples.get(playerId);
  if (!s || s.t.length === 0) return { matterPerMin: 0, energyPerMin: instantEnergy };
  const win = Math.max(1, Math.min(INCOME_HISTORY, Number.isFinite(windowSec) ? windowSec : INCOME_WINDOW));
  const from = now - win;
  let lo = 0, hi = s.t.length - 1; // first sample with t >= from
  while (lo < hi) { const mid = (lo + hi) >> 1; if (s.t[mid]! < from - 1e-9) lo = mid + 1; else hi = mid; }
  const span = now - s.t[lo]!;
  if (span < 1 - 1e-9) return { matterPerMin: 0, energyPerMin: instantEnergy };
  return {
    matterPerMin: Math.max(0, ((p.stats.matterGathered - s.matter[lo]!) / span) * 60),
    energyPerMin: Math.max(0, ((p.stats.energyGenerated - s.energy[lo]!) / span) * 60),
  };
}

/**
 * Workers currently assigned to a resource node: alive units whose current order is gather (walking to it, waiting,
 * gathering or carrying its cargo back) or returnCargo (they resume on it). Optional playerId filter.
 */
export function workersOnNode(world: World, nodeId: EntityId, playerId?: PlayerId): number {
  let n = 0;
  for (const e of world.list) {
    const g = e.gatherer;
    if (!g || !e.alive || g.nodeId !== nodeId || (playerId != null && e.owner !== playerId)) continue;
    const t = e.orders[0]?.type;
    if (t === 'gather' || t === 'returnCargo') n++;
  }
  return n;
}
